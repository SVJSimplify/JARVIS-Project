import os from 'os';
import path from 'path';
import { describe, it, expect, beforeEach } from 'vitest';
import * as fs from 'fs';

import { normalizeIR, generateArtifact, validateArtifact, validateOOXML } from '../src/main/artifact';

const ROOT = process.env.JARVIS_FILES_ROOT ?? path.join(os.tmpdir(), `jarvis-test-${process.pid}`);

const ir = (format: 'docx' | 'pdf' | 'pptx' | 'xlsx', extra: Record<string, unknown> = {}) => ({
  title: 'Q3 Field Report',
  format,
  subtitle: 'Generated by the artifact service test suite',
  sections: [
    { title: 'Summary', blocks: [{ type: 'paragraph', text: 'All field units reported green status this quarter.' }, { type: 'bullet', text: 'North reactor: nominal' }, { type: 'numbered', text: 'South bay: refitted' }] },
    {
      title: 'Inventory',
      blocks: [
        { type: 'table', rows: [['Item', 'Qty', 'Cost'], ['Arc reactor', '3', '₹10,000'], ['Gauntlet', '12', '₹42,000']] },
        { type: 'heading', text: 'Notes', level: 2 },
        { type: 'paragraph', text: 'Figures are illustrative.' },
      ],
    },
    { title: 'Closing', blocks: [{ type: 'pagebreak' }, { type: 'paragraph', text: 'End of quarterly summary.' }] },
  ],
  ...extra,
});

beforeEach(() => {
  fs.rmSync(path.join(ROOT, 'documents'), { recursive: true, force: true });
});

describe('normalizeIR — the model cannot feed the renderers garbage', () => {
  it('rejects a spec without title, format or sections, with reasons', () => {
    expect(normalizeIR({})?.warnings.join('; ')).toMatch(/title is required/);
    expect(normalizeIR({ title: 'x', format: 'docx' })?.warnings.join('; ')).toMatch(/at least one section/);
    expect(normalizeIR({ title: 'x', format: 'exe', sections: [{ blocks: [{ type: 'paragraph', text: 'a' }] }] }).ir).toBeNull();
    const bad = normalizeIR({ title: 'x', format: 'docx', sections: [{ title: 'kept', blocks: [{ type: 'laser', text: 'zap' }] }] });
    expect(bad.ir?.sections[0].blocks).toHaveLength(0);
    expect(bad.warnings.join(' ')).toMatch(/unknown block type/);
    // A nameless section with nothing usable is dropped entirely.
    expect(normalizeIR({ title: 'x', format: 'docx', sections: [{ blocks: [{ type: 'laser' }] }] }).ir).toBeNull();
  });

  it('caps runaway sections and clips oversized text', () => {
    const many = Array.from({ length: 60 }, (_, i) => ({ title: `s${i}`, blocks: [{ type: 'paragraph', text: 'x'.repeat(9000) }] }));
    const r = normalizeIR({ title: 'big', format: 'docx', sections: many });
    expect(r.ir?.sections.length).toBeLessThanOrEqual(40);
    expect(r.ir?.sections[0].blocks[0].text!.length).toBeLessThanOrEqual(8000);
  });
});

describe('generateArtifact — every format renders, REOPENS and validates', () => {
  for (const format of ['docx', 'pdf', 'pptx', 'xlsx'] as const) {
    it(`produces a valid ${format.toUpperCase()} that passes deep validation`, async () => {
      const spec = normalizeIR(ir(format));
      expect(spec.ir).toBeTruthy();
      const out = await generateArtifact(spec.ir!, `documents/field-report-${format}`);
      expect(out.validation).not.toMatch(/^FAILED/);
      expect(out.bytes).toBeGreaterThan(500);
      expect(fs.existsSync(path.join(ROOT, 'documents', `field-report-${format}.${format}`))).toBe(true);
      // The independent validator agrees (the double-check the tool result is built from).
      const again = await validateArtifact(path.join(ROOT, 'documents', `field-report-${format}.${format}`), format);
      expect(again.ok).toBe(true);
    }, 30_000);
  }

  it('xlsx workbooks actually re-read with exceljs: sheets, headers and rows are present', async () => {
    const spec = normalizeIR(ir('xlsx')).ir!;
    const out = await generateArtifact(spec, 'documents/inventory');
    expect(out.validation).toMatch(/valid xlsx/);
    const { Workbook } = await import('exceljs');
    const wb = new Workbook();
    await wb.xlsx.readFile(path.join(ROOT, 'documents', 'inventory.xlsx'));
    // The Inventory section lands on its own sheet with the table header row.
    const ws = wb.worksheets.find((w) => JSON.stringify(w.getRow(1).values).includes('Item'));
    expect(ws).toBeTruthy();
    expect(JSON.stringify(ws!.getRow(2).values)).toContain('Arc reactor');
  }, 30_000);

  it('pdf reopens with the expected page structure', async () => {
    const spec = normalizeIR(ir('pdf')).ir!;
    const out = await generateArtifact(spec, 'documents/report');
    expect(out.validation).toMatch(/page\(s\)/);
    const { PDFDocument } = await import('pdf-lib');
    const doc = await PDFDocument.load(fs.readFileSync(path.join(ROOT, 'documents', 'report.pdf')));
    expect(doc.getPageCount()).toBeGreaterThanOrEqual(2); // pagebreak in the last section
  }, 30_000);

  it('a corrupt "document" fails validation honestly', async () => {
    const fake = path.join(ROOT, 'documents', 'fake.xlsx');
    fs.mkdirSync(path.dirname(fake), { recursive: true });
    fs.writeFileSync(fake, 'this is not a spreadsheet');
    const v = await validateArtifact(fake, 'xlsx');
    expect(v.ok).toBe(false);
    expect(v.detail).toMatch(/container check failed|not a valid OOXML|workbook/);
    const emptyDocx = path.join(ROOT, 'documents', 'empty.docx');
    fs.writeFileSync(emptyDocx, Buffer.from([0x50, 0x4b, 0x03, 0x04]));
    expect((await validateOOXML(emptyDocx, 'docx')).ok).toBe(false);
  });

  it('the tool wrapper reports failure as NOT DONE and success with the validation line', async () => {
    const { artifactTools } = await import('../src/main/artifact');
    const ok = String(await artifactTools.make_document.run({ title: 'Meeting Notes', format: 'docx', path: 'documents/notes', sections: [{ blocks: [{ type: 'paragraph', text: 'hello' }] }] }));
    expect(ok).toMatch(/VALIDATION: reopened as a valid docx/);
    const bad = String(await artifactTools.make_document.run({ title: 'Broken', format: 'doc', path: 'documents/broken', sections: [{ blocks: [] }] }));
    expect(bad).toMatch(/NOT DONE/);
  });
});
